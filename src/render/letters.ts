/** Width of a text run in units at the given letter height. */
export function textWidth(text: string, height: number): number {
  const px = height / 7;
  return text.length * 6 * px - px;
}

/**
 * Build letters centred on the origin, standing on y = 0 and facing +z. Depth is along z.
 * Unknown characters render as a dot.
 */
export function textGeometry(pal: PaletteMap, text: string, height: number, depth: number, hexFace: string, hexSide: string): BufferGeometry {
  const px = height / 7;
  const parts: BufferGeometry[] = [];
  const upper = text.toUpperCase();
  const total = textWidth(upper, height);
  let cursor = -total / 2;
  for (const ch of upper) {
    const rows = FONT[ch] ?? FONT['.']!;
    // Merge horizontal runs into one block per row for fewer triangles.
    for (let r = 0; r < 7; r++) {
      const row = rows[r]!;
      let c = 0;
      while (c < 5) {
        if (row[c] === '1') {
          let e = c;
          while (e < 5 && row[e] === '1') e++;
          const w = (e - c) * px;
          const x = cursor + c * px + w / 2;
          const y = (6 - r) * px;
          parts.push(box(pal, hexSide, w, px, depth, x, y, 0));
          parts.push(box(pal, hexFace, w, px, 0.02, x, y, depth / 2 + 0.01));
          c = e;
        } else c++;
      }
    }
    cursor += 6 * px;
  }
  return merge(parts);
}

